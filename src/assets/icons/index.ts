function loadAsset(path: string): string {
  const url = assets[`./general/${path}`];
  if (!url) throw new Error(`Missing icon asset: ${path}`);
  return url;
}

const icons = Object.fromEntries(
  Object.entries(iconDefinitions).map(([name, path]) => [name, loadAsset(path)])
) as Record<keyof typeof iconDefinitions, string>;

export default icons;
